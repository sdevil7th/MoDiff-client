import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const packages = lock.packages ?? {};
const rootPackage = packages[''] ?? {};
const outputPath = join(root, 'public', 'THIRD_PARTY_LICENSES.txt');
const write = process.argv.includes('--write');

function parentPackagePath(packagePath) {
  return packagePath.replace(/(?:^|\/)node_modules\/(?:@[^/]+\/)?[^/]+$/, '');
}

function resolvePackagePath(fromPath, name) {
  let current = fromPath;
  while (true) {
    const candidate = current ? `${current}/node_modules/${name}` : `node_modules/${name}`;
    if (packages[candidate]) return candidate;
    if (!current) return null;
    const parent = parentPackagePath(current);
    if (parent === current) return null;
    current = parent;
  }
}

function dependencyRequests(entry) {
  const requests = new Map();
  for (const name of Object.keys(entry.dependencies ?? {})) requests.set(name, false);
  // Platform-specific optional packages are build/install helpers and are not
  // copied into the browser distribution. Their own package directories retain
  // their licenses; excluding them also keeps this generated web notice
  // identical on Linux, macOS, and Windows.
  for (const name of Object.keys(entry.peerDependencies ?? {})) {
    const optional = entry.peerDependenciesMeta?.[name]?.optional === true;
    if (!requests.has(name)) requests.set(name, optional);
  }
  return requests;
}

const selected = new Set();
const queue = Object.keys(rootPackage.dependencies ?? {}).map((name) => ({ fromPath: '', name, optional: false }));
while (queue.length > 0) {
  const request = queue.shift();
  const packagePath = resolvePackagePath(request.fromPath, request.name);
  if (!packagePath) {
    if (request.optional) continue;
    throw new Error(`Production dependency ${request.name} is absent below ${request.fromPath || '<root>'}.`);
  }
  if (selected.has(packagePath)) continue;
  selected.add(packagePath);
  for (const [name, optional] of dependencyRequests(packages[packagePath])) {
    queue.push({ fromPath: packagePath, name, optional });
  }
}

function licenseFiles(packageDirectory) {
  return readdirSync(packageDirectory)
    .filter((name) => /^(?:licen[cs]e|copying|notice)(?:[._-].*)?$/i.test(name))
    .filter((name) => existsSync(join(packageDirectory, name)))
    .sort((left, right) => left.localeCompare(right));
}

const records = [...selected]
  .map((packagePath) => {
    const packageDirectory = join(root, packagePath);
    const manifest = JSON.parse(readFileSync(join(packageDirectory, 'package.json'), 'utf8'));
    const files = licenseFiles(packageDirectory);
    if (files.length === 0) {
      throw new Error(`${manifest.name}@${manifest.version} has no root license/notice file.`);
    }
    return {
      identity: `${manifest.name}@${manifest.version}`,
      license: manifest.license ?? manifest.licenses ?? 'UNDECLARED',
      files: files.map((name) => ({ name, text: readFileSync(join(packageDirectory, name), 'utf8').trim() })),
    };
  })
  .sort((left, right) => left.identity.localeCompare(right.identity));

const projectNotices = readFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), 'utf8').trim();
const sections = [
  'MoDiff web client - production dependency licenses',
  '',
  'Generated deterministically from package-lock.json and the installed production dependency closure.',
  'Do not edit this file directly; run `npm run licenses:generate`.',
  '',
  '='.repeat(80),
  'MoDiff project-specific third-party notices',
  '='.repeat(80),
  '',
  projectNotices,
];

for (const record of records) {
  sections.push('', '='.repeat(80), record.identity, `Declared license: ${record.license}`, '='.repeat(80));
  for (const file of record.files) {
    sections.push('', `--- ${file.name} ---`, '', file.text);
  }
}

const generated = `${sections.join('\n')}\n`;
if (write) {
  writeFileSync(outputPath, generated, 'utf8');
  process.stdout.write(
    `Wrote ${records.length} production package license records to public/THIRD_PARTY_LICENSES.txt.\n`,
  );
} else {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    throw new Error('public/THIRD_PARTY_LICENSES.txt is stale. Run `npm run licenses:generate`.');
  }
  process.stdout.write(`Verified ${records.length} production package license records.\n`);
}
